const RANDOM_LOOKUPS: usize = 4096;

fn random_probes(keys: &[&'static str]) -> Vec<String> {
    let mut state = 0x9e37_79b9_7f4a_7c15u64;
    (0..RANDOM_LOOKUPS)
        .map(|lookup| {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            let pick = usize::try_from(state % keys.len() as u64).unwrap_or_default();
            let mut probe = keys[pick].as_bytes().to_vec();
            if lookup % 2 == 1 {
                let pos = usize::try_from(state >> 32).unwrap_or_default() % probe.len();
                probe[pos] ^= 0x01;
            }
            String::from_utf8(probe).unwrap_or_default()
        })
        .collect()
}

macro_rules! bench_dataset {
    ($c:expr, $name:literal, $phf:expr, $map:path, $fnc_map:path) => {{
        let keys: Vec<&'static str> = $phf.keys().copied().collect();
        let random = random_probes(&keys);

        let mut group = $c.benchmark_group(concat!($name, "/hits"));
        group.bench_function("phf", |b| {
            b.iter(|| {
                for key in &keys {
                    black_box($phf.get(black_box(*key)).is_some());
                }
            })
        });
        group.bench_function("hashify_map", |b| {
            b.iter(|| {
                for key in &keys {
                    black_box($map(black_box(key.as_bytes())).is_some());
                }
            })
        });
        group.bench_function("hashify_fnc_map", |b| {
            b.iter(|| {
                for key in &keys {
                    black_box($fnc_map(black_box(key.as_bytes())).is_some());
                }
            })
        });
        group.finish();

        let mut group = $c.benchmark_group(concat!($name, "/random"));
        group.bench_function("phf", |b| {
            b.iter(|| {
                for key in &random {
                    black_box($phf.get(black_box(key.as_str())).is_some());
                }
            })
        });
        group.bench_function("hashify_map", |b| {
            b.iter(|| {
                for key in &random {
                    black_box($map(black_box(key.as_bytes())).is_some());
                }
            })
        });
        group.bench_function("hashify_fnc_map", |b| {
            b.iter(|| {
                for key in &random {
                    black_box($fnc_map(black_box(key.as_bytes())).is_some());
                }
            })
        });
        group.finish();
    }};
}

fn bench_hashmaps(c: &mut Criterion) {
    bench_dataset!(c, "methods", METHODS, methods_map, methods_fnc_map);
    bench_dataset!(c, "imap", IMAP, imap_map, imap_fnc_map);
    bench_dataset!(c, "words", WORDS, words_map, words_fnc_map);
    bench_dataset!(c, "charsets", CHARSETS, charsets_map, charsets_fnc_map);
    bench_dataset!(c, "entities", ENTITIES, entities_map, entities_fnc_map);
}

criterion_group!(benches, bench_hashmaps);
criterion_main!(benches);
